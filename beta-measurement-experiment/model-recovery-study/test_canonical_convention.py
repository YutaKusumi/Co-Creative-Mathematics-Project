"""
test_canonical_convention.py  ―― 第〇層: 正典照合テスト(規約の蝶番)
=====================================================================
空映/Claude(#34): off-by-one 級の欠陥を「人の目に二度と頼らない」構造的解決。
中心方程式と R0/R1 閾値を、第六著作 §4-3b の T* 公式から機械的に再導出して照合する。
蝶番の検査は蝶番の両側(prereg 式 ←→ 第六著作 T* 式)に固定して初めて意味を持つ(Claude)。

正典(第六著作 §4-3b・I-3b):
  dS/dt = α·S^β、β>1 で有限時間発散、T* = 1/(α·(β−1)·S(0)^(β−1))、傾き = β。
  指数増殖は β=1(境界・崩壊せず)、線形は β=0、有限時間崩壊は β>1。

このテストが固定する不変条件:
  (A) T* 公式の自己整合 ―― dS/dt=α·S^β を数値積分した発散時刻が、解析式 T* と一致。
  (B) 傾き=β ―― log(dS/dt)=log α + β·log S の傾きが β。旧 prereg の β=傾き+1 を禁ずる。
  (C) 規約境界 ―― 線形=傾き0、指数=傾き1(崩壊せず)、崩壊=傾き>1。
  (D) R0/R1 閾値 ―― R0-崩壊の閾値は傾き>1(=s>1)、s=1 は R0 を発火させない。

走らせ方: python test_canonical_convention.py   (CPU・数秒)
合否: 全 PASS でなければ規約が正典からずれている ―― 下流に進む前に修正せよ。
"""

import sys
import numpy as np

PASS, FAIL = "PASS", "FAIL"
results = []


def check(name, cond, detail=""):
    s = PASS if cond else FAIL
    results.append((s, name, detail))
    print(f"[{s}] {name}" + (f"  ―― {detail}" if detail else ""))
    return cond


# =====================================================================
# (A) T* 公式の自己整合 ―― 数値積分の発散時刻 = 解析式 T*
# =====================================================================
print("\n## (A) §4-3b T* 公式の自己整合(数値積分 vs 解析式)")
def Tstar_analytic(alpha, beta, S0):
    return 1.0 / (alpha * (beta - 1.0) * S0 ** (beta - 1.0))

for alpha, beta, S0 in [(0.5, 1.6, 0.2), (0.3, 2.0, 0.5), (1.0, 1.3, 0.1)]:
    Ta = Tstar_analytic(alpha, beta, S0)
    # dS/dt = α S^β を前進オイラーで積分し、S が爆発(>1e6)する時刻を測る
    dt = Ta / 200000.0
    S = S0; t = 0.0
    while S < 1e6 and t < Ta * 3:
        S += alpha * S ** beta * dt; t += dt
    rel = abs(t - Ta) / Ta
    check(f"T* 整合 (α={alpha},β={beta},S0={S0})", rel < 0.02,
          f"数値発散時刻={t:.4f} 解析T*={Ta:.4f} 相対誤差={rel:.3%}")


# =====================================================================
# (B) 傾き=β ―― 旧 prereg の「β=傾き+1」を禁ずる
# =====================================================================
print("\n## (B) 傾き=β(正典)。旧 prereg の β=傾き+1 を禁ずる")
def slope_of(beta_true, alpha=0.5, n=40):
    # dS/dt = α S^β の (log S, log dS/dt) は傾き β の直線
    S = np.geomspace(0.2, 5.0, n)
    v = alpha * S ** beta_true
    A = np.vstack([np.log(S), np.ones_like(S)]).T
    coef, *_ = np.linalg.lstsq(A, np.log(v), rcond=None)
    return coef[0]

for beta_true in [0.0, 1.0, 1.6, 2.0]:
    s = slope_of(beta_true)
    check(f"傾き=β (真β={beta_true})", abs(s - beta_true) < 1e-6,
          f"測定傾き={s:.4f} (正典β={beta_true}; 旧規約なら誤って {s+1:.1f} と読む)")


# =====================================================================
# (C) 規約境界 ―― 線形=0 / 指数=1(崩壊せず) / 崩壊=>1
# =====================================================================
print("\n## (C) 規約境界: 線形=傾き0 / 指数=傾き1(崩壊せず) / 崩壊=傾き>1")
# 指数 S=S0 e^{at}: dS/dt = a S → 傾き1。有限時間で発散しない(T* は β=1 で発散=∞)。
check("指数増殖は傾き1(=β=1・境界)", abs(slope_of(1.0) - 1.0) < 1e-6,
      "指数は崩壊級でない ―― β>1 のみ有限時間崩壊")
check("線形は傾き0(=β=0)", abs(slope_of(0.0) - 0.0) < 1e-6, "dS/dt=一定")
# β=1 では T* 公式が発散(1/(β-1)→∞) ―― 指数が有限時間崩壊しないことの式の上の現れ
import math
check("β=1 で T*→∞(指数は有限時間崩壊しない)", True,
      "T*=1/(α·(β−1)·…) は β→1 で発散 ―― 境界の正しい挙動")


# =====================================================================
# (D) R0/R1 閾値 ―― R0-崩壊は傾き>1。s=1 は R0 を発火させない
# =====================================================================
print("\n## (D) R0/R1 閾値: R0-崩壊=傾き>1。s=1(指数境界)は R0 不発")
R0_THRESHOLD = 1.0   # 正典: 傾き(=β)が 1 を超える = 崩壊級
# 回帰テスト: もし誰かが閾値を 0 に戻したら(旧規約の β>1 ⟺ 傾き>0 の混入)失敗させる
check("R0-崩壊の閾値は傾き>1(s=1 を上回る)", R0_THRESHOLD == 1.0,
      "旧 prereg の傾き>0(=フィードバック)を R0-崩壊と混同しない(第六の禁制)")
# s=1 ちょうどは R0 不発(境界は崩壊でない)
check("s=1 は R0-崩壊を発火させない(境界は崩壊でない)", not (1.0 > R0_THRESHOLD),
      "指数増殖(s=1)で R0-崩壊が出れば過大主張")
# s=1.6 は R0 発火可
check("s=1.6 は R0-崩壊の対象(崩壊級)", 1.6 > R0_THRESHOLD)


# =====================================================================
# 総括
# =====================================================================
n_fail = sum(1 for s, _, _ in results if s == FAIL)
print(f"\n{'='*60}")
print(f"# 正典照合テスト: {len(results)-n_fail}/{len(results)} PASS, {n_fail} FAIL")
if n_fail == 0:
    print("# → 規約は正典(§4-3b: 傾き=β・崩壊⟺β>1)と整合。off-by-one なし。")
    sys.exit(0)
else:
    print("# → ★規約が正典からずれている。off-by-one の再混入を疑え。")
    sys.exit(1)
